"""Reproducible lockfile inventory and verbatim notices from exact installed packages.
Does not substitute a different version or imply legal approval for missing artifacts.
"""
import csv
import hashlib
import json
import os
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
lock = json.loads((root / "package-lock.json").read_text(encoding="utf-8"))
direct = {**lock["packages"][""].get("dependencies", {}), **lock["packages"][""].get("devDependencies", {})}
rows, notices = [], []
for package_path, item in lock["packages"].items():
    if not package_path:
        continue
    directory = root / package_path
    metadata_path = directory / "package.json"
    metadata = json.loads(metadata_path.read_text(encoding="utf-8")) if metadata_path.exists() else {}
    exact = metadata.get("version") == item.get("version")
    name = metadata.get("name") if exact else package_path.rsplit("node_modules/", 1)[-1]
    files = []
    if exact:
        for current, dirs, names in os.walk(directory):
            dirs[:] = [d for d in dirs if d not in ("node_modules", ".git")]
            for filename in names:
                if re.match(r"^(licen[cs]e|notice|copying|copyright)([._-].*)?$", filename, re.I):
                    path = Path(current) / filename
                    try:
                        contents = path.read_text(encoding="utf-8")
                    except UnicodeError:
                        continue
                    relative = path.relative_to(directory).as_posix()
                    files.append(relative)
                    notices.append((f"{name}@{item['version']} / {relative}", hashlib.sha256(path.read_bytes()).hexdigest(), contents))
    declared = metadata.get("license", item.get("license", "UNKNOWN")) if exact else item.get("license", "UNKNOWN")
    if not isinstance(declared, str):
        declared = json.dumps(declared, ensure_ascii=False)
    rows.append({"lock_path": package_path, "version": item.get("version", ""),
        "scope": ("direct" if name in direct else "transitive") + (" dev" if item.get("dev") else " runtime"),
        "source": item.get("resolved", ""), "license": declared, "notice_files": ";".join(sorted(files)),
        "project_modifications": "No vendored edits declared",
        "review": "EXACT_INSTALLED_NOTICES" if exact and files else "NOTICE_UNVERIFIED" if exact else "TARGET_ARTIFACT_UNVERIFIED"})
target = root / "docs/licenses"
target.mkdir(exist_ok=True)
with (target / "dependencies.csv").open("w", encoding="utf-8", newline="") as output:
    writer = csv.DictWriter(output, fieldnames=list(rows[0]), quoting=csv.QUOTE_ALL)
    writer.writeheader()
    writer.writerows(rows)
with (target / "THIRD_PARTY_NOTICES.md").open("w", encoding="utf-8", newline="\n") as output:
    output.write("# Exact installed package notices\n\nGenerated by scripts/inventory-licenses.py. Includes package-bundled notices; optional target artifacts missing locally remain unresolved in dependencies.csv. Project assets have separate rights. No legal approval inferred.\n\n")
    for title, digest, content in sorted(notices):
        output.write(f"## {title}\n\nSHA-256: {digest}\n\n")
        output.write("````text\n" + content.rstrip() + "\n````\n\n")
summary = {"lockfile_sha256": hashlib.sha256((root / "package-lock.json").read_bytes()).hexdigest(),
    "lock_entries": len(rows), "exact_installed_with_notices": sum(r["review"] == "EXACT_INSTALLED_NOTICES" for r in rows),
    "unresolved": sum(r["review"] != "EXACT_INSTALLED_NOTICES" for r in rows), "notice_files": len(notices),
    "scope": "Current host installation; Linux deployment and Edge Deno artifacts need their own exact notice inventory"}
(target / "inventory-summary.json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
print(json.dumps(summary))
